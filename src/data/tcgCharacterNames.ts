// Función para obtener la lista de nombres según el juego TCG
export const getTcgCharacterSuggestions = (
  gameType: string,
  query: string,
  allPokemonNames: string[]
): { title: string; color: string; items: string[] } => {
  let sourceList: string[] = [];
  let title = 'Sugerencias';
  let color = '#ffcb05';

  switch (gameType) {
    case 'POKEMON':
      sourceList = allPokemonNames;
      title = 'Sugerencias de Pokémon';
      color = '#ffcb05';
      break;
    case 'ONEPIECE':
      sourceList = ALL_ONE_PIECE_CHARACTERS;
      title = 'Personajes de One Piece';
      color = '#06b6d4';
      break;
    case 'YUGIOH':
      sourceList = ALL_YUGIOH_CARDS;
      title = 'Monstruos y Cartas de Yu-Gi-Oh!';
      color = '#a855f7';
      break;
    case 'MAGIC':
      sourceList = ALL_MAGIC_CARDS;
      title = 'Cartas Icónicas de Magic: The Gathering';
      color = '#f59e0b';
      break;
    default:
      sourceList = allPokemonNames;
      title = 'Sugerencias';
      color = '#ffcb05';
  }

  const q = (query || '').trim().toLowerCase();
  if (!q) {
    // Si no ha escrito nada, mostrar los primeros 25 en orden A-Z
    return {
      title,
      color,
      items: sourceList.slice(0, 25)
    };
  }

  const startsWith = sourceList.filter(name => name.toLowerCase().startsWith(q));
  const includes = sourceList.filter(name => !name.toLowerCase().startsWith(q) && name.toLowerCase().includes(q));
  
  return {
    title,
    color,
    items: [...startsWith, ...includes].slice(0, 35)
  };
};
